CREATE OR REPLACE FUNCTION public.update_polarimeter_deviation(
  p_id bigint,
  p_expected_version integer,
  p_actor_user_id bigint,
  p_investigation text,
  p_root_cause text,
  p_corrective_action text,
  p_preventive_action text,
  p_responsible_user_id bigint,
  p_target_completion_date date,
  p_status text,
  p_change_data jsonb
)
RETURNS SETOF public.polarimeter_deviations
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  current_case public.polarimeter_deviations%ROWTYPE;
  actor_role public.app_role;
  actor_active boolean;
  assignee_role public.app_role;
  assignee_active boolean;
  current_status_rank integer;
  next_status_rank integer;
  changed public.polarimeter_deviations%ROWTYPE;
BEGIN
  SELECT * INTO current_case FROM public.polarimeter_deviations WHERE id = p_id FOR UPDATE;
  IF NOT FOUND OR current_case.version <> p_expected_version THEN
    RAISE EXCEPTION 'Deviation conflict: reload the latest case before saving' USING ERRCODE = '40001';
  END IF;
  SELECT role, is_active INTO actor_role, actor_active FROM public.app_users WHERE id = p_actor_user_id;
  IF actor_active IS DISTINCT FROM true OR actor_role = 'viewer' THEN
    RAISE EXCEPTION 'An active editor is required to update this deviation' USING ERRCODE = '42501';
  END IF;
  IF p_status = 'closed' AND actor_role <> 'admin' THEN
    RAISE EXCEPTION 'Only an administrator may close a deviation' USING ERRCODE = '42501';
  END IF;
  IF p_status NOT IN ('open', 'investigating', 'actions-planned', 'closed') THEN
    RAISE EXCEPTION 'Invalid deviation status' USING ERRCODE = '23514';
  END IF;
  current_status_rank := CASE current_case.status
    WHEN 'open' THEN 1 WHEN 'investigating' THEN 2 WHEN 'actions-planned' THEN 3 WHEN 'closed' THEN 4 END;
  next_status_rank := CASE p_status
    WHEN 'open' THEN 1 WHEN 'investigating' THEN 2 WHEN 'actions-planned' THEN 3 WHEN 'closed' THEN 4 END;
  IF next_status_rank < current_status_rank THEN
    RAISE EXCEPTION 'Deviation status cannot move backwards' USING ERRCODE = '23514';
  END IF;
  IF p_status = 'closed' THEN
    IF current_case.status <> 'actions-planned' THEN
      RAISE EXCEPTION 'Plan corrective actions before closing a deviation' USING ERRCODE = '23514';
    END IF;
    IF length(trim(coalesce(p_investigation, ''))) = 0
       OR length(trim(coalesce(p_root_cause, ''))) = 0
       OR length(trim(coalesce(p_corrective_action, ''))) = 0
       OR p_responsible_user_id IS NULL
       OR p_target_completion_date IS NULL THEN
      RAISE EXCEPTION 'Investigation, root cause, corrective action, responsible person and target date are required for closure' USING ERRCODE = '23514';
    END IF;
  END IF;
  IF p_responsible_user_id IS NOT NULL THEN
    SELECT role, is_active INTO assignee_role, assignee_active FROM public.app_users WHERE id = p_responsible_user_id;
    IF assignee_active IS DISTINCT FROM true OR assignee_role = 'viewer' THEN
      RAISE EXCEPTION 'The responsible person must be an active editor or administrator' USING ERRCODE = '23514';
    END IF;
  END IF;
  UPDATE public.polarimeter_deviations
    SET investigation = p_investigation,
        root_cause = p_root_cause,
        corrective_action = p_corrective_action,
        preventive_action = p_preventive_action,
        responsible_user_id = p_responsible_user_id,
        target_completion_date = p_target_completion_date,
        status = p_status,
        version = version + 1,
        updated_by_user_id = p_actor_user_id,
        updated_at = now(),
        closed_at = CASE WHEN p_status = 'closed' THEN now() ELSE NULL END
    WHERE id = p_id
    RETURNING * INTO changed;
  INSERT INTO public.polarimeter_deviation_events
    (deviation_id, actor_user_id, event_type, change_data)
  VALUES (p_id, p_actor_user_id, 'updated', coalesce(p_change_data, '{}'::jsonb));
  RETURN NEXT changed;
END;
$$;

REVOKE ALL ON FUNCTION public.update_polarimeter_deviation(bigint, integer, bigint, text, text, text, text, bigint, date, text, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.update_polarimeter_deviation(bigint, integer, bigint, text, text, text, text, bigint, date, text, jsonb) TO service_role;

-- Atomic, role-checked technical review. This serializes against record edits and
-- lifecycle decisions by locking the exact saved record version.
CREATE OR REPLACE FUNCTION public.submit_polarimeter_technical_review(
  p_validation_record_id bigint,
  p_expected_record_version integer,
  p_reviewer_user_id bigint,
  p_decision text,
  p_comments text,
  p_rejection_reason text,
  p_outstanding_issues jsonb
)
RETURNS SETOF public.record_technical_reviews
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  current_record public.validation_records%ROWTYPE;
  reviewer_role public.app_role;
  reviewer_active boolean;
  created_review public.record_technical_reviews%ROWTYPE;
BEGIN
  SELECT * INTO current_record
    FROM public.validation_records
    WHERE id = p_validation_record_id
    FOR UPDATE;
  IF NOT FOUND OR current_record.instrument_key <> 'polarimeter' THEN
    RAISE EXCEPTION 'Polarimeter record not found' USING ERRCODE = 'P0002';
  END IF;
  IF current_record.lifecycle_status <> 'draft' THEN
    RAISE EXCEPTION 'Only a saved draft Polarimeter record can be reviewed' USING ERRCODE = '23514';
  END IF;
  IF current_record.record_version <> p_expected_record_version THEN
    RAISE EXCEPTION 'Review conflict: the record changed; reload before reviewing' USING ERRCODE = '40001';
  END IF;
  SELECT role, is_active INTO reviewer_role, reviewer_active
    FROM public.app_users WHERE id = p_reviewer_user_id;
  IF reviewer_active IS DISTINCT FROM true OR reviewer_role IS DISTINCT FROM 'admin'::public.app_role THEN
    RAISE EXCEPTION 'An active administrator is required to perform a technical review' USING ERRCODE = '42501';
  END IF;
  IF current_record.validated_by_user_id = p_reviewer_user_id THEN
    RAISE EXCEPTION 'The analyst cannot perform the independent technical review' USING ERRCODE = '42501';
  END IF;
  IF p_decision NOT IN ('accepted', 'rejected') OR length(trim(coalesce(p_comments, ''))) = 0 THEN
    RAISE EXCEPTION 'A valid technical-review decision and comments are required' USING ERRCODE = '23514';
  END IF;
  IF p_decision = 'rejected' AND length(trim(coalesce(p_rejection_reason, ''))) = 0 THEN
    RAISE EXCEPTION 'A rejection reason is required for a rejected technical review' USING ERRCODE = '23514';
  END IF;
  IF jsonb_typeof(coalesce(p_outstanding_issues, '[]'::jsonb)) <> 'array'
     OR jsonb_array_length(coalesce(p_outstanding_issues, '[]'::jsonb)) > 30 THEN
    RAISE EXCEPTION 'Outstanding issues must be a bounded JSON array' USING ERRCODE = '23514';
  END IF;
  IF p_decision = 'accepted' THEN
    IF current_record.result_status <> 'pass'
       OR (current_record.result_data #>> '{polarimeterData,overallResult}') IS DISTINCT FROM 'pass'
       OR (current_record.result_data #>> '{polarimeterData,protocolSnapshot,protocolStatus}') IS DISTINCT FROM 'approved' THEN
      RAISE EXCEPTION 'Technical acceptance requires passing results and a verified protocol' USING ERRCODE = '23514';
    END IF;
    IF jsonb_array_length(coalesce(p_outstanding_issues, '[]'::jsonb)) > 0 THEN
      RAISE EXCEPTION 'Resolve outstanding issues before acceptance' USING ERRCODE = '23514';
    END IF;
  END IF;
  INSERT INTO public.record_technical_reviews
    (validation_record_id, record_version, reviewer_user_id, decision, comments, rejection_reason, outstanding_issues)
  VALUES
    (p_validation_record_id, p_expected_record_version, p_reviewer_user_id,
     p_decision, trim(p_comments), nullif(trim(coalesce(p_rejection_reason, '')), ''),
     coalesce(p_outstanding_issues, '[]'::jsonb))
  RETURNING * INTO created_review;
  RETURN NEXT created_review;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_polarimeter_technical_review(bigint, integer, bigint, text, text, text, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.submit_polarimeter_technical_review(bigint, integer, bigint, text, text, text, jsonb) TO service_role;

-- Atomic approval/rejection: lifecycle status, approval history and the audit
-- event are committed together, after checking the latest current-version review.
CREATE OR REPLACE FUNCTION public.decide_polarimeter_validation_record(
  p_validation_record_id bigint,
  p_expected_record_version integer,
  p_approver_user_id bigint,
  p_decision text,
  p_reason text,
  p_summary text,
  p_metadata jsonb
)
RETURNS SETOF public.validation_records
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  current_record public.validation_records%ROWTYPE;
  current_review public.record_technical_reviews%ROWTYPE;
  approver_role public.app_role;
  approver_active boolean;
  changed_record public.validation_records%ROWTYPE;
BEGIN
  SELECT * INTO current_record
    FROM public.validation_records
    WHERE id = p_validation_record_id
    FOR UPDATE;
  IF NOT FOUND OR current_record.instrument_key <> 'polarimeter' THEN
    RAISE EXCEPTION 'Polarimeter record not found' USING ERRCODE = 'P0002';
  END IF;
  IF current_record.lifecycle_status <> 'draft' THEN
    RAISE EXCEPTION 'Validation record has already been decided' USING ERRCODE = '23514';
  END IF;
  IF current_record.record_version <> p_expected_record_version THEN
    RAISE EXCEPTION 'Approval conflict: the record changed; reload before deciding' USING ERRCODE = '40001';
  END IF;
  SELECT role, is_active INTO approver_role, approver_active
    FROM public.app_users WHERE id = p_approver_user_id;
  IF approver_active IS DISTINCT FROM true OR approver_role IS DISTINCT FROM 'admin'::public.app_role THEN
    RAISE EXCEPTION 'An active administrator is required to decide validation records' USING ERRCODE = '42501';
  END IF;
  IF p_decision NOT IN ('approved', 'rejected') THEN
    RAISE EXCEPTION 'Invalid lifecycle decision' USING ERRCODE = '23514';
  END IF;
  IF p_decision = 'rejected' AND length(trim(coalesce(p_reason, ''))) = 0 THEN
    RAISE EXCEPTION 'A rejection reason is required for a Polarimeter lifecycle rejection' USING ERRCODE = '23514';
  END IF;
  IF p_decision = 'approved' THEN
    IF current_record.result_status <> 'pass'
       OR (current_record.result_data #>> '{polarimeterData,overallResult}') IS DISTINCT FROM 'pass' THEN
      RAISE EXCEPTION 'Failed Polarimeter tests cannot be approved' USING ERRCODE = '23514';
    END IF;
    IF (current_record.result_data #>> '{polarimeterData,protocolSnapshot,protocolStatus}') IS DISTINCT FROM 'approved' THEN
      RAISE EXCEPTION 'Polarimeter approval is blocked until the protocol is verified and approved' USING ERRCODE = '23514';
    END IF;
    SELECT * INTO current_review
      FROM public.record_technical_reviews
      WHERE validation_record_id = p_validation_record_id
      ORDER BY created_at DESC, id DESC
      LIMIT 1;
    IF NOT FOUND
       OR current_review.decision <> 'accepted'
       OR current_review.record_version <> current_record.record_version
       OR jsonb_array_length(current_review.outstanding_issues) > 0 THEN
      RAISE EXCEPTION 'A current accepted independent technical review is required before approval' USING ERRCODE = '23514';
    END IF;
    IF current_review.reviewer_user_id = current_record.validated_by_user_id
       OR current_review.reviewer_user_id = p_approver_user_id
       OR current_record.validated_by_user_id = p_approver_user_id THEN
      RAISE EXCEPTION 'Analyst, reviewer and approver must be different users' USING ERRCODE = '42501';
    END IF;
  END IF;
  UPDATE public.validation_records
    SET lifecycle_status = p_decision,
        approved_by_user_id = p_approver_user_id,
        approved_at = now(),
        updated_at = now()
    WHERE id = p_validation_record_id
      AND lifecycle_status = 'draft'
      AND record_version = p_expected_record_version
  RETURNING * INTO changed_record;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Approval conflict: the record changed; reload before deciding' USING ERRCODE = '40001';
  END IF;
  INSERT INTO public.record_approvals
    (validation_record_id, approver_user_id, decision, reason)
  VALUES
    (p_validation_record_id, p_approver_user_id, p_decision,
     nullif(trim(coalesce(p_reason, '')), ''));
  INSERT INTO public.audit_events
    (validation_record_id, actor_user_id, action, previous_status, next_status, summary, metadata)
  VALUES
    (p_validation_record_id, p_approver_user_id, p_decision,
     current_record.lifecycle_status, p_decision,
     coalesce(nullif(trim(p_summary), ''), 'Polarimeter lifecycle decision recorded'),
     coalesce(p_metadata, '{}'::jsonb));
  RETURN NEXT changed_record;
END;
$$;

