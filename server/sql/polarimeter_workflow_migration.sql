-- Harden CAPA transition rules at the database transaction boundary as well.

CREATE OR REPLACE FUNCTION public.validate_polarimeter_retest_link()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  original public.validation_records%ROWTYPE;
BEGIN
  IF NEW.retest_of_record_id IS NULL THEN
    IF NEW.retest_reason IS NOT NULL THEN
      RAISE EXCEPTION 'A retest reason requires an original record' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.instrument_key <> 'polarimeter'
     OR length(trim(coalesce(NEW.retest_reason, ''))) < 10 THEN
    RAISE EXCEPTION 'A linked retest requires Polarimeter equipment and a reason of at least 10 characters' USING ERRCODE = '23514';
  END IF;
  SELECT * INTO original
    FROM public.validation_records
    WHERE id = NEW.retest_of_record_id;
  IF NOT FOUND
     OR original.instrument_key <> 'polarimeter'
     OR original.result_status <> 'fail'
     OR original.instrument_id <> NEW.instrument_id THEN
    RAISE EXCEPTION 'A retest must reference an existing failed Polarimeter record for the same equipment' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS polarimeter_retest_link_guard ON public.validation_records;
CREATE TRIGGER polarimeter_retest_link_guard
  BEFORE INSERT OR UPDATE OF retest_of_record_id, retest_reason
  ON public.validation_records
  FOR EACH ROW EXECUTE FUNCTION public.validate_polarimeter_retest_link();

-- Create failed-test cases inside the same database transaction as their record.
-- The deviation INSERT trigger above is the sole writer of each creation event;
-- application-level upserts become idempotent confirmation/recovery only.
CREATE OR REPLACE FUNCTION public.create_polarimeter_failure_cases()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  polarimeter_data jsonb;
  protocol jsonb;
  metrics jsonb;
  test_results jsonb;
  repeatability_method text;
  linearity_metric text;
  actual_result text;
  acceptance_limit text;
  deviation_values text;
  protocol_status text;
BEGIN
  IF TG_OP = 'UPDATE'
     AND OLD.instrument_key = 'polarimeter'
     AND OLD.result_status = 'fail' THEN
    RETURN NEW;
  END IF;
  IF NEW.instrument_key IS DISTINCT FROM 'polarimeter'
     OR NEW.result_status IS DISTINCT FROM 'fail'
     OR jsonb_typeof(NEW.result_data) IS DISTINCT FROM 'object' THEN
    RETURN NEW;
  END IF;
  polarimeter_data := NEW.result_data -> 'polarimeterData';
  IF jsonb_typeof(polarimeter_data) IS DISTINCT FROM 'object'
     OR polarimeter_data ->> 'schemaVersion' IS DISTINCT FROM '2' THEN
    RETURN NEW;
  END IF;
  protocol := polarimeter_data -> 'protocolSnapshot';
  metrics := polarimeter_data -> 'calculatedMetrics';
  test_results := polarimeter_data -> 'testResults';
  protocol_status := coalesce(protocol ->> 'protocolStatus', 'pending-verification');

  IF test_results ->> 'accuracy' = 'fail' THEN
    actual_result := coalesce(metrics ->> 'specificRotation', 'Not defined') || ' °';
    acceptance_limit := coalesce(protocol #>> '{accuracy,lowerLimit}', 'Not defined')
      || ' to ' || coalesce(protocol #>> '{accuracy,upperLimit}', 'Not defined')
      || ' ° specific rotation';
    INSERT INTO public.polarimeter_deviations
      (validation_record_id, test_key, actual_result, acceptance_limit,
       protocol_status, created_by_user_id, updated_by_user_id)
    VALUES
      (NEW.id, 'accuracy', actual_result, acceptance_limit,
       protocol_status, NEW.validated_by_user_id, NEW.validated_by_user_id)
    ON CONFLICT (validation_record_id, test_key) DO NOTHING;
  END IF;

  IF test_results ->> 'repeatability' = 'fail' THEN
    repeatability_method := protocol #>> '{repeatability,method}';
    IF repeatability_method = 'maximum-range' THEN
      actual_result := coalesce(metrics ->> 'repeatabilityRange', 'Not defined') || ' ° range';
      acceptance_limit := '≤ ' || coalesce(protocol #>> '{repeatability,tolerance}', 'Not defined') || ' ° range';
    ELSIF repeatability_method = 'sample-standard-deviation' THEN
      actual_result := coalesce(metrics ->> 'repeatabilitySampleStandardDeviation', 'Not defined') || ' ° sample SD';
      acceptance_limit := '≤ ' || coalesce(protocol #>> '{repeatability,tolerance}', 'Not defined') || ' ° sample SD';
    ELSIF repeatability_method = 'rsd-percent' THEN
      actual_result := coalesce(metrics ->> 'repeatabilityRsdPercent', 'Not defined') || ' % RSD';
      acceptance_limit := '≤ ' || coalesce(protocol #>> '{repeatability,tolerance}', 'Not defined') || ' % RSD';
    ELSE
      IF jsonb_typeof(metrics -> 'repeatabilityDeviations') = 'array' THEN
        SELECT string_agg(value, ', ' ORDER BY ordinal)
          INTO deviation_values
          FROM jsonb_array_elements_text(metrics -> 'repeatabilityDeviations')
            WITH ORDINALITY AS deviation_item(value, ordinal);
      ELSE
        deviation_values := NULL;
      END IF;
      actual_result := coalesce(deviation_values, 'Not defined') || ' ° absolute deviations';
      acceptance_limit := 'each absolute deviation ≤ '
        || coalesce(protocol #>> '{repeatability,tolerance}', 'Not defined') || ' °';
    END IF;
    INSERT INTO public.polarimeter_deviations
      (validation_record_id, test_key, actual_result, acceptance_limit,
       protocol_status, created_by_user_id, updated_by_user_id)
    VALUES
      (NEW.id, 'repeatability', actual_result, acceptance_limit,
       protocol_status, NEW.validated_by_user_id, NEW.validated_by_user_id)
    ON CONFLICT (validation_record_id, test_key) DO NOTHING;
  END IF;

  IF test_results ->> 'linearity' = 'fail' THEN
    linearity_metric := protocol #>> '{linearity,metric}';
    IF linearity_metric = 'r2' THEN
      actual_result := coalesce(metrics ->> 'coefficientOfDetermination', 'Not defined') || ' R²';
      acceptance_limit := '≥ ' || coalesce(protocol #>> '{linearity,minimumMetric}', 'Not defined') || ' R²';
    ELSE
      actual_result := coalesce(metrics ->> 'correlationCoefficient', 'Not defined') || ' r';
      acceptance_limit := '≥ ' || coalesce(protocol #>> '{linearity,minimumMetric}', 'Not defined') || ' r';
    END IF;
    INSERT INTO public.polarimeter_deviations
      (validation_record_id, test_key, actual_result, acceptance_limit,
       protocol_status, created_by_user_id, updated_by_user_id)
    VALUES
      (NEW.id, 'linearity', actual_result, acceptance_limit,
       protocol_status, NEW.validated_by_user_id, NEW.validated_by_user_id)
    ON CONFLICT (validation_record_id, test_key) DO NOTHING;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS polarimeter_failure_cases_from_record ON public.validation_records;
CREATE TRIGGER polarimeter_failure_cases_from_record
  AFTER INSERT OR UPDATE ON public.validation_records
  FOR EACH ROW EXECUTE FUNCTION public.create_polarimeter_failure_cases();

COMMIT;

