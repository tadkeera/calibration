-- Measurement/failure evidence is immutable; only CAPA workflow fields may change.
CREATE OR REPLACE FUNCTION public.prevent_polarimeter_failure_evidence_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Polarimeter failure records are retained; create a linked retest instead';
  END IF;
  IF OLD.instrument_key = 'polarimeter' AND OLD.result_status = 'fail' AND (
    NEW.instrument_key IS DISTINCT FROM OLD.instrument_key OR
    NEW.result_status IS DISTINCT FROM OLD.result_status OR
    NEW.instrument_name IS DISTINCT FROM OLD.instrument_name OR
    NEW.instrument_id IS DISTINCT FROM OLD.instrument_id OR
    NEW.sop_number IS DISTINCT FROM OLD.sop_number OR
    NEW.form_number IS DISTINCT FROM OLD.form_number OR
    NEW.result_data IS DISTINCT FROM OLD.result_data OR
    NEW.pharmacist_name IS DISTINCT FROM OLD.pharmacist_name OR
    NEW.validated_by_user_id IS DISTINCT FROM OLD.validated_by_user_id OR
    NEW.retest_of_record_id IS DISTINCT FROM OLD.retest_of_record_id OR
    NEW.retest_reason IS DISTINCT FROM OLD.retest_reason
  ) THEN
    RAISE EXCEPTION 'Failed Polarimeter measurements are immutable; create a linked retest instead';
  END IF;
  RETURN NEW;
END;
$$;

