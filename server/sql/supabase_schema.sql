create extension if not exists pgcrypto;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'app_role') then
    create type public.app_role as enum ('admin', 'user', 'viewer');
  end if;
end $$;

create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  open_id text not null unique,
  name text,
  email text not null unique,
  login_method text not null default 'local',
  role public.app_role not null default 'user',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_signed_in timestamptz not null default now()
);

create table if not exists public.validation_records (
  id bigint generated by default as identity primary key,
  instrument_key text not null,
  instrument_name text not null,
  instrument_id text not null,
  sop_number text not null,
  form_number text not null,
  result_status text not null check (result_status in ('pass', 'fail')),
  lifecycle_status text not null default 'draft' check (lifecycle_status in ('draft', 'approved', 'rejected')),
  result_data jsonb not null,
  pharmacist_name text not null,
  validated_by_user_id bigint not null references public.app_users(id),
  approved_by_user_id bigint references public.app_users(id),
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists validation_records_owner_idx on public.validation_records(validated_by_user_id);
create index if not exists validation_records_lifecycle_idx on public.validation_records(lifecycle_status);
create index if not exists validation_records_created_at_idx on public.validation_records(created_at desc);

create table if not exists public.audit_events (
  id bigint generated by default as identity primary key,
  validation_record_id bigint not null references public.validation_records(id) on delete cascade,
  actor_user_id bigint not null references public.app_users(id),
  action text not null check (action in ('created', 'updated', 'approved', 'rejected', 'exported')),
  previous_status text,
  next_status text,
  summary text not null,
  metadata jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_events_record_idx on public.audit_events(validation_record_id);
create index if not exists audit_events_actor_idx on public.audit_events(actor_user_id);
create index if not exists audit_events_created_at_idx on public.audit_events(created_at desc);

create table if not exists public.record_approvals (
  id bigint generated by default as identity primary key,
  validation_record_id bigint not null references public.validation_records(id) on delete cascade,
  approver_user_id bigint not null references public.app_users(id),
  decision text not null check (decision in ('approved', 'rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.instrument_profiles (
  id bigint generated by default as identity primary key,
  instrument_key text not null unique,
  name_ar text not null,
  name_en text not null,
  instrument_id text not null,
  sop_number text not null,
  manufacturer text not null,
  model text not null,
  serial_number text not null,
  form_number text not null,
  accent text not null,
  updated_by_user_id bigint not null references public.app_users(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.instrument_change_events (
  id bigint generated by default as identity primary key,
  instrument_key text not null,
  editor_user_id bigint not null references public.app_users(id),
  previous_data jsonb,
  next_data jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists instrument_change_events_key_idx on public.instrument_change_events(instrument_key);
create index if not exists instrument_change_events_editor_idx on public.instrument_change_events(editor_user_id);

create table if not exists public.validation_settings (
  device_key text primary key,
  settings jsonb not null,
  updated_by_user_id bigint references public.app_users(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.legacy_imports (
  source_table text not null,
  source_id bigint not null,
  target_table text not null,
  target_id bigint,
  imported_at timestamptz not null default now(),
  primary key (source_table, source_id)
);

alter table public.app_users enable row level security;
alter table public.validation_records enable row level security;
alter table public.audit_events enable row level security;
alter table public.record_approvals enable row level security;
alter table public.instrument_profiles enable row level security;
alter table public.instrument_change_events enable row level security;
alter table public.validation_settings enable row level security;
alter table public.legacy_imports enable row level security;
